import matplotlib.pyplot as plt
import numpy as np
print("\n" + "=" * 50)
print("ЗАДАЧА 5: ВСТРЕЧА ДВУХ ВЕЛОСИПЕДИСТОВ")
print("=" * 50)
V1 = 15
V2 = 20
Δt = 1
print(f"Скорость первого велосипедиста: V₁ = {V1} км/ч")
print(f"Скорость второго велосипедиста: V₂ = {V2} км/ч")
print(f"Второй выехал на {Δt} час позже")
S0 = V1 * Δt
V_отн = V2 - V1
t_встречи = S0 / V_отн
t1_общее = Δt + t_встречи
S_встречи = V1 * t1_общее
print("\n" + "=" * 50)
print("РЕШЕНИЕ:")
print("=" * 50)
print(f"1. За {Δt} час первый проехал: S₀ = V₁ × Δt = {V1} × {Δt} = {S0} км")
print(f"2. Относительная скорость: V_отн = V₂ - V₁ = {V2} - {V1} = {V_отн} км/ч")
print(f"3. Время встречи после выезда второго: t = S₀ / V_отн = {S0} / {V_отн} = {t_встречи:.2f} ч")
print(f"4. Время встречи от начального момента: {Δt} + {t_встречи:.2f} = {t1_общее:.2f} ч")
print(f"5. Расстояние до встречи: S = V₁ × t₁ = {V1} × {t1_общее:.2f} = {S_встречи:.2f} км")
часы_встречи = 8 + t1_общее
часы = int(часы_встречи)
минуты = int((часы_встречи - часы) * 60)
print(f"\nОТВЕТ: Второй велосипедист догонит первого")
print(f" через {t_встречи:.2f} часа после своего выезда")
print(f" в {часы:02d}:{минуты:02d}")
print(f" на расстоянии {S_встречи:.1f} км от пункта отправления")
print("\nТаблица движения:")
print("-" * 50)
print("Время | Расстояние 1-го | Расстояние 2-го")
print("-" * 50)
for час in range(8, 12):
    for минута in [0, 30]:
        время_ч = час + минута / 60
        if время_ч >= 8:
            S1 = V1 * (время_ч - 8)
        else:
            S1 = 0
        if время_ч >= 9:
            S2 = V2 * (время_ч - 9)
        else:
            S2 = 0
        if время_ч == int(часы_встречи) and abs(минута - (часы_встречи - int(часы_встречи)) * 60) < 1:
            метка = "← ВСТРЕЧА"
        else:
            метка = ""
        print(f"{час:2d}:{минута:02d} | {S1:9.1f} км | {S2:9.1f} км {метка}")
print("\nСтроим график движения...")
t1 = np.linspace(0, 5, 100)
t2 = np.linspace(1, 5, 100)
s1 = V1 * t1
s2 = V2 * (t2 - 1)
s2 = np.where(t2 < 1, 0, s2)
plt.figure(figsize=(10, 6))
plt.plot(t1 + 8, s1, 'b-', linewidth=2, label='Первый велосипедист (15 км/ч)')
plt.plot(t2 + 8, s2, 'r-', linewidth=2, label='Второй велосипедист (20 км/ч)')
plt.plot(часы_встречи, S_встречи, 'go', markersize=10, label=f'Встреча в {часы:02d}:{минуты:02d}')
plt.title('График движения двух велосипедистов', fontsize=14)
plt.xlabel('Время (часы)', fontsize=12)
plt.ylabel('Расстояние от пункта отправления (км)', fontsize=12)
plt.grid(True, alpha=0.3)
plt.legend(fontsize=10)
plt.xlim(7.5, 13)
plt.ylim(0, 70)
plt.xticks(range(8, 14), [f'{i}:00' for i in range(8, 14)])
plt.annotate(f'Встреча\n{часы:02d}:{минуты:02d}\n{S_встречи:.1f} км',
             xy=(часы_встречи, S_встречи),
             xytext=(часы_встречи + 0.5, S_встречи - 10),
             arrowprops=dict(arrowstyle='->', color='green'),
             bbox=dict(boxstyle='round,pad=0.3', facecolor='yellow', alpha=0.7))
plt.tight_layout()
plt.show()
print("График построен и отображен")